function build(part, map, file) {
  const out = {};
  const ids = part.questions.map(q => q.id);
  const missing = ids.filter(id => !map[id]);
  const extra = Object.keys(map).filter(id => !ids.includes(id));
  const badCodes = Object.entries(map).filter(([id,v]) => v[0] !== 'null' && !dots.has(v[0]));
  const badWhy = Object.entries(map).filter(([id,v]) => v[2].trim().split(/\s+/).length > 12);
  if (missing.length || extra.length || badCodes.length || badWhy.length) {
    console.log('MISSING', file, missing);
    console.log('EXTRA', file, extra);
    console.log('BADCODES', file, badCodes);
    console.log('LONGWHY', file, badWhy);
    process.exit(1);
  }
  for (const id of ids) {
    const [code, confidence, why] = map[id];
    out[id] = { code: code === 'null' ? null : code, confidence, why };
  }
  fs.writeFileSync(file, JSON.stringify(out, null, 2) + '\n', 'utf8');
  const conf = {high:0, medium:0, low:0};
  const nulls = Object.values(out).filter(v => v.code === null).length;
  Object.values(out).forEach(v => conf[v.confidence]++);
  console.log(file, 'ids=' + ids.length, 'nulls=' + nulls, JSON.stringify(conf));
}
