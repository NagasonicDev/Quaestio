problems = []
for part in (1, 2):
    with open(os.path.join(BASE, f"earth-environmental-science.part{part}.json"), encoding="utf-8") as f:
        data = json.load(f)
    codes = {d["code"] for d in data["dots"]}
    ids = [q["id"] for q in data["questions"]]
    missing = [i for i in ids if i not in M]
    if missing: problems.append(f"part{part} missing ids: {missing}")
    out = {}
    for i in ids:
        code, conf, why = M[i]
        if code is not None and code not in codes:
            problems.append(f"{i}: invalid code {code}")
        if conf not in ("high", "medium", "low"):
            problems.append(f"{i}: bad confidence {conf}")
        if len(why.split()) > 12:
            problems.append(f"{i}: why too long ({len(why.split())} words)")
        out[i] = {"code": code, "confidence": conf, "why": why}
    path = os.path.join(BASE, f"earth-environmental-science.part{part}.out.json")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(out, f, indent=2, ensure_ascii=False)
        f.write("\n")
    print(f"part{part}: wrote {len(out)} entries -> {path}")

if problems:
    print("PROBLEMS:")
    for p in problems: print(" -", p)
else:
    print("validation: OK (ids exact, codes in dots, confidences valid, why <=12 words)")

